for (const shapeData of SHAPES_DEGREES) {
	const [degreeShape, name] = shapeData;
	const penalty = shapeData.length > 2 ? shapeData[2] : 0;
	const shape = degreeShape.map(x => degreeMap[x]);
	const forbid5 = (shapeData.length > 3)
		? shapeData[3]
		: (degreeShape.includes("b5") || degreeShape.includes("#5"));
	SHAPES.push([shape, name, forbid5, degreeShape, penalty]);
}

function getDegreeAccordingToChord(note, shape) {
	if (note === 0) return "1";
	if (note === 4) return "3";
	if (note === 7) return "5";
	if (note === 10) return "b7";
	if (note === 11) return "7";

	for (const degree in degreeMap) {
		if (!shape.includes(degree)) continue;
		if (degreeMap[degree] === note) return degree;
	}

	return null;
}

function getDegreesAccordingToChord(notes, shape) {
	const degrees = [];

	for (const note of notes) {
		degrees.push(getDegreeAccordingToChord(note, shape));
	}

	return degrees;
}

